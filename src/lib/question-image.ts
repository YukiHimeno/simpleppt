/**
 * 把 AI 生成 SVG 里的“问号小人”占位符（<g data-question-person x=… y=… size=…/>）
 * 替换成真实图片的 <image> 元素。本地参数化渲染器会直接输出 <image>，不受影响。
 * 仅浏览器端使用（DOMParser / XMLSerializer）。
 */
export function resolveSlideImages(svg: string): string {
  if (!svg.includes('data-question-person')) return svg
  const doc = new DOMParser().parseFromString(svg, 'image/svg+xml')
  const root = doc.documentElement
  for (const el of Array.from(root.querySelectorAll('[data-question-person]'))) {
    const x = Number(el.getAttribute('x') ?? 0)
    const y = Number(el.getAttribute('y') ?? 0)
    const s = Number(el.getAttribute('size') ?? 60)
    const h = s
    const w = Math.round(s * 0.85) // 306×360
    const img = doc.createElementNS('http://www.w3.org/2000/svg', 'image')
    img.setAttribute('href', QUESTION_PERSON_DATA_URL)
    img.setAttribute('x', String(Math.round(x - w)))
    img.setAttribute('y', String(Math.round(y - h / 2)))
    img.setAttribute('width', String(w))
    img.setAttribute('height', String(h))
    img.setAttribute('preserveAspectRatio', 'xMidYMid meet')
    el.replaceWith(img)
  }
  return new XMLSerializer().serializeToString(root)
}
